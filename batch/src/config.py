"""バッチ全体の設定値。

しきい値をここに集約しているのは、ランキングの「意味」を決めている数字が
コードのあちこちに散らばると、後から仕様を追いにくくなるため。
"""

from pathlib import Path

# --- パス ---------------------------------------------------------------

BATCH_DIR = Path(__file__).resolve().parent.parent
PROJECT_DIR = BATCH_DIR.parent

# JPX「東証上場銘柄一覧」Excel。手動ダウンロードしてリポジトリで管理する。
JPX_EXCEL = BATCH_DIR / "data" / "data_j.xls"

# フロントエンドが fetch する生成物。Vite の public 配下に置くことで
# ビルド時にそのまま dist へコピーされる。
OUTPUT_JSON = PROJECT_DIR / "web" / "public" / "data" / "top30.json"

# yfinance がタイムゾーン情報をキャッシュする SQLite の置き場所。
# 既定だとユーザーのホーム配下に作られ、CI で毎回作り直しになるため明示する。
CACHE_DIR = BATCH_DIR / ".cache"


# --- ユニバース ---------------------------------------------------------

# 仕様: 東証上場の「普通株のみ」。ETF・ETN・REIT・インフラファンド・
# 出資証券・外国株・PRO Market はここに含めないことで除外される。
TARGET_MARKETS = {
    "プライム（内国株式）": "プライム",
    "スタンダード（内国株式）": "スタンダード",
    "グロース（内国株式）": "グロース",
}


# --- 取得 ---------------------------------------------------------------

# --- 1 段目: スクリーニング（yf.download の一括取得） -------------------

# yf.download に一度に渡すティッカー数。
# 100 で約 7.5 秒／バッチ。大きくしすぎると 1 件の失敗の巻き添え範囲が広がる。
BATCH_SIZE = 100

# 直近 12 か月の配当を拾えれば足りるが、期末配当の計上ずれを吸収するため
# 余裕をもって 15 か月分取得する。
HISTORY_PERIOD = "15mo"

# バッチ単位のリトライ回数と待機秒数。
MAX_RETRIES = 3
RETRY_WAIT_SEC = 5

# バッチ間に挟む待機。Yahoo 側にまとめてリクエストを浴びせないための保険。
INTER_BATCH_WAIT_SEC = 0.5

# 取得できなかった銘柄をまとめて取り直すラウンド数と、その間の待機秒数。
# 終盤でレート制限に当たると 1 ラウンド目で数百銘柄がごっそり欠けるため、
# 冷ましてから拾い直さないとランキングから実在の高配当銘柄が抜け落ちる。
RETRY_ROUNDS = 3
RETRY_ROUND_WAIT_SEC = 30


# --- 2 段目: 候補の確定（Ticker.info の個別取得） -----------------------

# 1 段目の推定利回りの上位から何銘柄を検証対象にするか。
# 一括取得の配当は株式分割の調整が銘柄によって不揃いで、利回りが過大に出る
# ケースがある（例: 日本製鉄は分割前の配当が混ざり 10.6% と算出される）。
# そこで 1 段目はふるいと割り切り、上位候補だけ Yahoo 公式の配当フィールドで
# 確定させる。TOP30 の 5 倍の枠を取れば、1 段目の誤差で真の上位が
# こぼれ落ちることはまず起きない。
CANDIDATE_POOL = 150

# Ticker.info の呼び出し間隔とリトライ。
INFO_INTERVAL_SEC = 0.3
INFO_MAX_RETRIES = 3
INFO_RETRY_WAIT_SEC = 10


# --- ランキング ---------------------------------------------------------

TOP_N = 30

# これを超える利回りはデータ異常（株式併合の反映漏れ等）とみなして除外する。
# 実在の高配当銘柄でも 20% 台が上限であり、50% 超はまず値がおかしい。
MAX_PLAUSIBLE_YIELD = 50.0

# 配当実績（TTM）が会社予想の何倍を超えたら「特別配当の疑い」とするか。
# 記念配当・特別配当を出した期は実績だけが跳ね上がり、翌期には戻る。
# 例: アイティメディアは実績 100 円に対し予想 50 円で、利回りが倍近く見える。
SPECIAL_DIVIDEND_RATIO = 1.5

# 業種別 TOP いくつを画面に出すか。
SECTOR_TOP_N = 5
